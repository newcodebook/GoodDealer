function parseArguments(argv) {
  let profile = "local";
  let prepareOnly = false;

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--") {
      continue;
    }
    if (argument === "--prepare") {
      prepareOnly = true;
      continue;
    }
    if (argument === "--profile") {
      profile = argv[index + 1];
      index += 1;
      continue;
    }
    if (argument.startsWith("--profile=")) {
      profile = argument.slice("--profile=".length);
      continue;
    }
    throw new Error(`Unknown argument: ${argument}`);
  }

  if (!supportedProfiles.has(profile)) {
    throw new Error(
      `Unsupported profile "${profile}". Expected one of: ${[...supportedProfiles].join(", ")}.`,
    );
  }

  return { prepareOnly, profile };
}

function childEnvironment() {
  const environment = { ...process.env };
  delete environment.WP0_GITHUB_TOKEN;
  return environment;
}

function run(binary, args, options = {}) {
  return spawnSync(binary, args, {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 128 * 1024 * 1024,
    env: childEnvironment(),
    ...options,
  });
}

function probe(binary, args) {
  const result = run(binary, args, { timeout: 5_000 });
  if (result.status !== 0) {
    return "unavailable";
  }
  return result.stdout.trim();
}

function sha256(content) {
  return createHash("sha256").update(content).digest("hex");
}

function splitNullTerminated(value) {
  return value.split("\0").filter(Boolean);
}

function commaSeparatedEnvironment(name) {
  return (process.env[name] ?? "")
    .split(",")
    .map((value) => value.trim())
    .filter(Boolean);
}

function gitBytes(args) {
  const result = run("git", args, { encoding: null });
  return result.status === 0 ? result.stdout ?? Buffer.alloc(0) : null;
}

function hashUntrackedFiles(paths) {
  return paths.map((path) => {
    const absolutePath = resolve(root, path);
    const stat = lstatSync(absolutePath);
    if (stat.isSymbolicLink()) {
      const target = readlinkSync(absolutePath);
      return {
        path,
        kind: "symlink",
        mode: stat.mode,
        bytes: Buffer.byteLength(target),
        sha256: sha256(target),
      };
    }
    const content = readFileSync(absolutePath);
    return {
      path,
      kind: "file",
      mode: stat.mode,
      bytes: content.length,
      sha256: sha256(content),
    };
  });
}

function readRepositoryState() {
  const status = run("git", ["status", "--porcelain=v1", "--untracked-files=all"]);
  const pathCommands = [
    ["diff", "--name-only", "-z"],
    ["diff", "--cached", "--name-only", "-z"],
    ["ls-files", "--others", "--exclude-standard", "-z"],
  ];
  const changedPaths = new Set();

  for (const args of pathCommands) {
    const result = run("git", args);
    if (result.status === 0) {
      for (const path of splitNullTerminated(result.stdout)) {
        changedPaths.add(path);
      }
    }
  }

  const untracked = run("git", ["ls-files", "--others", "--exclude-standard", "-z"]);
  const untrackedPaths =
    untracked.status === 0 ? splitNullTerminated(untracked.stdout).sort() : [];
  const unstagedDiff = gitBytes(["diff", "--binary", "--no-ext-diff"]);
  const stagedDiff = gitBytes(["diff", "--cached", "--binary", "--no-ext-diff"]);
  const untrackedFiles = untracked.status === 0 ? hashUntrackedFiles(untrackedPaths) : [];
  const dirtyMaterial = {
    unstagedDiffSha256: unstagedDiff === null ? null : sha256(unstagedDiff),
    stagedDiffSha256: stagedDiff === null ? null : sha256(stagedDiff),
    untrackedFiles,
  };

  return {
    headCommit: probe("git", ["rev-parse", "HEAD"]),
    headTree: probe("git", ["rev-parse", "HEAD^{tree}"]),
    dirty: status.status === 0 ? status.stdout.length > 0 : null,
    statusAvailable: status.status === 0,
    changedPaths: [...changedPaths].sort(),
    dirtyMaterial: {
      ...dirtyMaterial,
      contentDigest: sha256(JSON.stringify(dirtyMaterial)),
    },
  };
}

function repositoryInputStable(initial, final) {
  return Boolean(
    initial?.statusAvailable &&
      final?.statusAvailable &&
      initial.headCommit === final.headCommit &&
      initial.headTree === final.headTree &&
      initial.dirtyMaterial.contentDigest === final.dirtyMaterial.contentDigest,
  );
}

function technicalEligibility(manifest) {
  const reasons = [];
  const initial = manifest.repository.initial;
  const final = manifest.repository.final;
  if (manifest.phase !== "complete") {
    reasons.push("validation-not-complete");
  }
  if (
    !initial?.statusAvailable ||
    (final !== null && !final.statusAvailable) ||
    (manifest.phase === "complete" && final === null)
  ) {
    reasons.push("repository-state-unavailable");
  }
  if (initial?.dirty || final?.dirty) {
    reasons.push("dirty-worktree");
  }
  if (final && !repositoryInputStable(initial, final)) {
    reasons.push("repository-input-changed-during-run");
  }
  if (manifest.ci !== null && !manifest.ci.jobUrl) {
    reasons.push("ci-job-url-unavailable");
  }
  if (!manifest.executionContext.valid) {
    reasons.push("runner-context-mismatch");
  }
  if (manifest.validations.some((validation) => validation.exitCode !== 0)) {
    reasons.push("validation-failed");
  }
  return {
    eligible: reasons.length === 0,
    reasons,
    scope: "technical-evidence-only; never represents Gate closure",
  };
}

function readExecutionContext() {
  const expectedPlatform = process.env.WP0_EXPECTED_PLATFORM ?? null;
  const expectedArch = process.env.WP0_EXPECTED_ARCH ?? null;
  const actualPlatform = platform();
  const actualArch = arch();
  const ci = process.env.GITHUB_ACTIONS === "true";
  const expectedContextPresent = Boolean(expectedPlatform && expectedArch);

  return {
    expected: { platform: expectedPlatform, arch: expectedArch },
    actual: {
      platform: actualPlatform,
      arch: actualArch,
      runnerOs: process.env.RUNNER_OS ?? null,
      runnerArch: process.env.RUNNER_ARCH ?? null,
      imageOs: process.env.ImageOS ?? null,
      imageVersion: process.env.ImageVersion ?? null,
    },
    valid:
      !ci ||
      (expectedContextPresent &&
        expectedPlatform === actualPlatform &&
        expectedArch === actualArch),
  };
}

function hashKeyInputs() {
  return keyInputPaths.map((path) => {
    const absolutePath = resolve(root, path);
    if (!existsSync(absolutePath)) {
      return { path, present: false, sha256: null };
    }
    const content = readFileSync(absolutePath);
    return { path, present: true, sha256: sha256(content) };
  });
}

function profileDefinition(profile) {
  const pnpm = platformExecutable("pnpm");
  const common = [
    {
      id: "platform-neutral-checks",
      binary: pnpm,
      args: ["check:platform-neutral"],
    },
    { id: "rust-format", binary: "cargo", args: ["fmt", "--all", "--check"] },
  ];
  const portableRust = [
    {
      id: "portable-rust-lint",
      binary: "cargo",
      args: ["clippy", ...portableCrates, "--", "-D", "warnings"],
    },
    {
      id: "portable-rust-tests",
      binary: "cargo",
      args: ["test", ...portableCrates],
    },
  ];
  const nativeRust = [
    {
      id: "native-rust-lint",
      binary: "cargo",
      args: ["clippy", "--workspace", "--all-targets", "--", "-D", "warnings"],
    },
    {
      id: "native-rust-tests",
      binary: "cargo",
      args: ["test", "--workspace", "--all-targets"],
    },
  ];

  if (profile === "quality") {
    return {
      resolvedProfile: "quality",
      applicability: "Platform-neutral checks for the Ubuntu quality runner.",
      commands: [
        {
          id: "dependency-vulnerability-gate",
          binary: pnpm,
          args: ["audit", "--audit-level", "high"],
        },
        {
          id: "rust-dependency-vulnerability-gate",
          binary: "cargo",
          args: ["audit"],
        },
        ...common,
        ...portableRust,
      ],
    };
  }

  if (profile === "native") {
    return {
      resolvedProfile: "native",
      applicability:
        "Native compile checks on a supported desktop runner; this does not build, bundle, sign, or publish a Tauri application artifact.",
      commands: [
        ...common,
        {
          id: "desktop-frontend-build",
          binary: pnpm,
          args: ["--filter", "@gooddealer/desktop", "build"],
        },
        ...nativeRust,
      ],
    };
  }

  if (platform() === "linux") {
    return {
      resolvedProfile: "local-portable",
      applicability:
        "Linux is not a supported desktop target; local evidence excludes desktop and non-portable workspace crates.",
      commands: [...common, ...portableRust],
    };
  }

  return {
    resolvedProfile: "local-native",
    applicability:
      "Local native compile checks for a supported macOS or Windows host; this is not a Tauri release or bundle build.",
    commands: [
      ...common,
      {
        id: "desktop-frontend-build",
        binary: pnpm,
        args: ["--filter", "@gooddealer/desktop", "build"],
      },
      ...nativeRust,
    ],
  };
}

async function resolveCiEvidence() {
  const serverUrl = process.env.GITHUB_SERVER_URL;
  const repository = process.env.GITHUB_REPOSITORY;
  const runId = process.env.GITHUB_RUN_ID;
  if (!serverUrl || !repository || !runId) {
    return null;
  }

  const runAttempt = process.env.GITHUB_RUN_ATTEMPT ?? "1";
  const jobName = process.env.WP0_CI_JOB_NAME ?? process.env.GITHUB_JOB ?? null;
  const runUrl = `${serverUrl}/${repository}/actions/runs/${runId}`;
  const ci = {
    provider: "github-actions",
    workflow: process.env.GITHUB_WORKFLOW ?? null,
    runId,
    runAttempt,
    runUrl,
    jobKey: process.env.GITHUB_JOB ?? null,
    jobName,
    jobUrl: null,
    jobUrlResolution: "unavailable",
  };
  const token = process.env.WP0_GITHUB_TOKEN;
  const apiUrl = process.env.GITHUB_API_URL;
  if (!token || !apiUrl || !jobName) {
    ci.jobUrlResolution = "missing-api-context";
    return ci;
  }

  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 5_000);
  try {
    const response = await fetch(
      `${apiUrl}/repos/${repository}/actions/runs/${runId}/attempts/${runAttempt}/jobs?per_page=100`,
      {
        headers: {
          Accept: "application/vnd.github+json",
          Authorization: `Bearer ${token}`,
          "X-GitHub-Api-Version": "2022-11-28",
        },
        signal: controller.signal,
      },
    );
    if (!response.ok) {
      ci.jobUrlResolution = `github-api-http-${response.status}`;
      return ci;
    }
    const payload = await response.json();
    const jobs = Array.isArray(payload.jobs) ? payload.jobs : [];
    const exactMatch = jobs.find((job) => job.name === jobName);
    const keyMatch = jobs.find((job) => job.name === ci.jobKey);
    const currentJob = exactMatch ?? keyMatch;
    if (currentJob?.html_url) {
      ci.jobUrl = currentJob.html_url;
      ci.jobUrlResolution = "github-api";
    } else {
      ci.jobUrlResolution = "job-not-found";
    }
  } catch (error) {
    ci.jobUrlResolution = error instanceof Error ? error.name : "github-api-error";
  } finally {
    clearTimeout(timeout);
  }

  return ci;
}

function executeValidation(definition, index) {
  const command = definition;
  const sequence = String(index + 1).padStart(2, "0");
  const logStem = `${sequence}-${command.id}`;
  const stdoutPath = resolve(logDirectory, `${logStem}.stdout.log`);
  const stderrPath = resolve(logDirectory, `${logStem}.stderr.log`);
  const startedAt = new Date();
  const result = spawnSync(command.binary, command.args, {
    cwd: root,
    encoding: null,
    maxBuffer: 128 * 1024 * 1024,
    env: childEnvironment(),
  });
  const finishedAt = new Date();
  const stdout = result.stdout ?? Buffer.alloc(0);
  let stderr = result.stderr ?? Buffer.alloc(0);
  if (result.error) {
    stderr = Buffer.concat([stderr, Buffer.from(`${result.error.stack ?? result.error.message}\n`)]);
  }
  const exitCode = result.status ?? (result.error?.code === "ENOENT" ? 127 : 1);

  writeFileSync(stdoutPath, stdout);
  writeFileSync(stderrPath, stderr);
  if (stdout.length > 0) {
    process.stdout.write(stdout);
  }
  if (stderr.length > 0) {
    process.stderr.write(stderr);
  }

  return {
    id: command.id,
    command: [command.binary, ...command.args],
    startedAt: startedAt.toISOString(),
    finishedAt: finishedAt.toISOString(),
    durationMs: finishedAt.getTime() - startedAt.getTime(),
    exitCode,
    signal: result.signal,
    stdout: {
      path: relative(root, stdoutPath),
      bytes: stdout.length,
      sha256: sha256(stdout),
    },
    stderr: {
      path: relative(root, stderrPath),
      bytes: stderr.length,
      sha256: sha256(stderr),
    },
  };
}

