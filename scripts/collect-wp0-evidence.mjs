function parseArguments(argv) {
  let profile = "local";
  let prepareOnly = false;
  let slice = null;

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--") {
      continue;
    }
    if (argument === "--prepare") {
      prepareOnly = true;
      continue;
    }
    if (argument === "--profile") {
      profile = argv[index + 1];
      index += 1;
      continue;
    }
    if (argument.startsWith("--profile=")) {
      profile = argument.slice("--profile=".length);
      continue;
    }
    if (argument === "--slice") {
      slice = argv[index + 1];
      index += 1;
      continue;
    }
    if (argument.startsWith("--slice=")) {
      slice = argument.slice("--slice=".length);
      continue;
    }
    throw new Error(`Unknown argument: ${argument}`);
  }

  if (!supportedProfiles.has(profile)) {
    throw new Error(
      `Unsupported profile "${profile}". Expected one of: ${[...supportedProfiles].join(", ")}.`,
    );
  }

  if (slice !== null && !supportedSlices.has(slice)) {
    throw new Error(
      `Unsupported slice "${slice}". Expected one of: ${[...supportedSlices].join(", ")}.`,
    );
  }

  return { prepareOnly, profile, slice };
}

function childEnvironment() {
  const environment = { ...process.env };
  delete environment.WP0_GITHUB_TOKEN;
  delete environment.EVIDENCE_GITHUB_TOKEN;
  return environment;
}

function run(binary, args, options = {}) {
  return spawnSync(binary, args, {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 128 * 1024 * 1024,
    env: childEnvironment(),
    ...options,
  });
}

function probe(binary, args) {
  const result = run(binary, args, { timeout: 5_000 });
  if (result.status !== 0) {
    return "unavailable";
  }
  return result.stdout.trim();
}

function sha256(content) {
  return createHash("sha256").update(content).digest("hex");
}

function splitNullTerminated(value) {
  return value.split("\0").filter(Boolean);
}

function commaSeparatedEnvironment(name) {
  return (process.env[name] ?? "")
    .split(",")
    .map((value) => value.trim())
    .filter(Boolean);
}

function gitBytes(args) {
  const result = run("git", args, { encoding: null });
  return result.status === 0 ? result.stdout ?? Buffer.alloc(0) : null;
}

function hashUntrackedFiles(paths) {
  return paths.map((path) => {
    const absolutePath = resolve(root, path);
    const stat = lstatSync(absolutePath);
    if (stat.isSymbolicLink()) {
      const target = readlinkSync(absolutePath);
      return {
        path,
        kind: "symlink",
        mode: stat.mode,
        bytes: Buffer.byteLength(target),
        sha256: sha256(target),
      };
    }
    const content = readFileSync(absolutePath);
    return {
      path,
      kind: "file",
      mode: stat.mode,
      bytes: content.length,
      sha256: sha256(content),
    };
  });
}

function readRepositoryState() {
  const status = run("git", ["status", "--porcelain=v1", "--untracked-files=all"]);
  const pathCommands = [
    ["diff", "--name-only", "-z"],
    ["diff", "--cached", "--name-only", "-z"],
    ["ls-files", "--others", "--exclude-standard", "-z"],
  ];
  const changedPaths = new Set();
  let pathsAvailable = true;

  for (const args of pathCommands) {
    const result = run("git", args);
    if (result.status === 0) {
      for (const path of splitNullTerminated(result.stdout)) {
        changedPaths.add(path);
      }
    } else {
      pathsAvailable = false;
    }
  }

  const untracked = run("git", ["ls-files", "--others", "--exclude-standard", "-z"]);
  const untrackedPaths =
    untracked.status === 0 ? splitNullTerminated(untracked.stdout).sort() : null;
  const unstagedDiff = gitBytes(["diff", "--binary", "--no-ext-diff"]);
  const stagedDiff = gitBytes(["diff", "--cached", "--binary", "--no-ext-diff"]);
  const untrackedFiles = untrackedPaths === null ? [] : hashUntrackedFiles(untrackedPaths);
  const dirtyMaterial = {
    unstagedDiffSha256: unstagedDiff === null ? null : sha256(unstagedDiff),
    stagedDiffSha256: stagedDiff === null ? null : sha256(stagedDiff),
    untrackedFiles,
  };
  const statusAvailable = Boolean(
    status.status === 0 &&
      pathsAvailable &&
      untrackedPaths !== null &&
      unstagedDiff !== null &&
      stagedDiff !== null,
  );

  return {
    headCommit: probe("git", ["rev-parse", "HEAD"]),
    headTree: probe("git", ["rev-parse", "HEAD^{tree}"]),
    dirty:
      statusAvailable
        ? repositoryMaterialDirty({ stagedDiff, unstagedDiff, untrackedPaths })
        : null,
    statusAvailable,
    changedPaths: [...changedPaths].sort(),
    dirtyMaterial: {
      ...dirtyMaterial,
      contentDigest: sha256(JSON.stringify(dirtyMaterial)),
    },
  };
}

function repositoryInputStable(initial, final) {
  return Boolean(
    initial?.statusAvailable &&
      final?.statusAvailable &&
      initial.headCommit === final.headCommit &&
      initial.headTree === final.headTree &&
      initial.dirtyMaterial.contentDigest === final.dirtyMaterial.contentDigest,
  );
}

function technicalEligibility(manifest) {
  const reasons = [];
  const initial = manifest.repository.initial;
  const final = manifest.repository.final;
  if (manifest.phase !== "complete") {
    reasons.push("validation-not-complete");
  }
  if (
    !initial?.statusAvailable ||
    (final !== null && !final.statusAvailable) ||
    (manifest.phase === "complete" && final === null)
  ) {
    reasons.push("repository-state-unavailable");
  }
  if (initial?.dirty || final?.dirty) {
    reasons.push("dirty-worktree");
  }
  if (final && !repositoryInputStable(initial, final)) {
    reasons.push("repository-input-changed-during-run");
  }
  if (manifest.ci !== null && !manifest.ci.jobUrl) {
    reasons.push("ci-job-url-unavailable");
  }
  if (!manifest.executionContext.valid) {
    reasons.push("runner-context-mismatch");
  }
  if (manifest.validations.some((validation) => validation.exitCode !== 0)) {
    reasons.push("validation-failed");
  }
  if (!sliceEvidenceValid(manifest.sliceEvidence)) {
    reasons.push("slice-evidence-invalid");
  }
  if (sliceEvidenceIgnored(manifest.sliceEvidence)) {
    reasons.push("keychain-probe-ignored");
  }
  return {
    eligible: reasons.length === 0,
    reasons,
    scope: "technical-evidence-only; never represents Gate closure",
  };
}

function sliceEvidenceValid(sliceEvidence) {
  if (sliceEvidence === null) {
    return true;
  }
  const report = sliceEvidence.report;
  if (sliceEvidence.slice === "account-gate") {
    return Boolean(
      sliceEvidence.present &&
        report?.schemaVersion === 1 &&
        report.fixtureOnly === true &&
        report.productionRoutesRegistered === false &&
        report.rawCredentialFieldsAbsent === true &&
        report.internalAccountSellable === false &&
        report.requiredInputsPresent === true &&
        report.accountVectors?.valid > 0 &&
        report.accountVectors?.invalid > 0 &&
        report.deviceVectors?.valid > 0 &&
        report.deviceVectors?.invalid > 0 &&
        Array.isArray(report.inputs) &&
        report.inputs.every(
          (input) => input.bytes > 0 && /^[0-9a-f]{64}$/.test(input.sha256),
        )
    );
  }
  if (sliceEvidence.slice === "cloud-boundary") {
    return Boolean(sliceEvidence.present && cloudBoundaryReportPassesPolicy(report));
  }
  if (sliceEvidence.slice === "keychain") {
    return Boolean(
      sliceEvidence.present &&
        (keychainCanaryReportPassesPolicy(report) ||
          keychainCanaryReportIsHonestIgnore(report)),
    );
  }
  if (sliceEvidence.slice === "backup") {
    return Boolean(
      sliceEvidence.present &&
        report?.schemaVersion === 1 &&
        report.aeadCrate === "chacha20poly1305" &&
        report.aeadCrateVersion === "0.11.0" &&
        report.exportProducesSealedEnvelope === true &&
        report.noPlaintextInEnvelope === true &&
        report.noCanaryInEnvelope === true &&
        report.noSqliteHeaderInEnvelope === true &&
        report.manifestDigestRecomputePasses === true &&
        report.aeadRoundtripSucceeds === true &&
        report.tamperedCiphertextRejected === true &&
        report.truncatedEnvelopeRejected === true &&
        report.swappedPackageRejected === true &&
        report.restoredSizeMatchesOriginal === true &&
        Array.isArray(report.scans) &&
        report.scans.length >= 2 &&
        report.scans.every(
          (scan) =>
            scan.bytes > 0 &&
            /^[0-9a-f]{64}$/.test(scan.sha256) &&
            scan.canaryAbsent === true &&
            scan.sqliteHeaderAbsent === true,
        ),
    );
  }
  if (sliceEvidence.slice === "sqlcipher-bundle") {
    return Boolean(
      sliceEvidence.present &&
        report?.schemaVersion === 1 &&
        report.tauriReleaseBuild === true &&
        report.bundleProduced === true &&
        report.bundleKind === (platform() === "win32" ? "msi" : "app") &&
        report.bundledExecutableExecuted === true &&
        report.sqlcipherVersion === "4.17.0 community" &&
        report.sqliteVersion === "3.53.3" &&
        report.databaseEncrypted === true &&
        report.correctKeyReadable === true &&
        report.wrongKeyRejected === true &&
        report.temporaryDatabaseRemoved === true &&
        report.releaseExecutable?.bytes > 0 &&
        /^[0-9a-f]{64}$/.test(report.releaseExecutable?.sha256 ?? "") &&
        report.bundledExecutable?.bytes > 0 &&
        /^[0-9a-f]{64}$/.test(report.bundledExecutable?.sha256 ?? "") &&
        report.bundleArtifact?.bytes > 0 &&
        report.bundleArtifact?.fileCount > 0 &&
        /^[0-9a-f]{64}$/.test(report.bundleArtifact?.sha256 ?? "")
    );
  }
  return Boolean(
    sliceEvidence.present &&
      report?.schemaVersion === 1 &&
      report.sqlcipherVersion === "4.17.0 community" &&
      report.sqliteVersion === "3.53.3" &&
      sqlcipherRequiredChecks.every((check) => report[check] === true) &&
      Array.isArray(report.scans) &&
      report.scans.length >= 7 &&
      report.scans.every(
        (scan) =>
          scan.bytes > 0 &&
          /^[0-9a-f]{64}$/.test(scan.sha256) &&
          scan.canaryAbsent === true &&
          scan.sqliteHeaderAbsent === true,
      ),
  );
}

function sliceEvidenceIgnored(sliceEvidence) {
  return Boolean(
    sliceEvidence?.slice === "keychain" &&
      sliceEvidence.present &&
      keychainCanaryReportIsHonestIgnore(sliceEvidence.report),
  );
}

