function writeManifest() {
  manifest.generatedAt = new Date().toISOString();
  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
}

// Write an initial artifact before any validation command so an interrupted run
// still leaves an explicit incomplete evidence record.
writeManifest();

if (!options.prepareOnly && process.exitCode !== 2) {
  for (const [index, command] of definition.commands.entries()) {
    try {
      manifest.validations.push(executeValidation(command, index));
    } catch (error) {
      manifest.validations.push({
        id: command.id,
        command: [command.binary, ...command.args],
        exitCode: 1,
        collectionError: error instanceof Error ? error.message : String(error),
      });
    }
    writeManifest();
  }
  manifest.repository.final = readRepositoryState();
  manifest.finishedAt = new Date().toISOString();
  manifest.phase = "complete";
  manifest.technicalEligibility = technicalEligibility(manifest);
  const validationsPassed = manifest.validations.every(
    (validation) => validation.exitCode === 0,
  );
  const ciRepositoryValid =
    manifest.ci === null ||
    (!manifest.repository.initial.dirty &&
      !manifest.repository.final.dirty &&
      repositoryInputStable(manifest.repository.initial, manifest.repository.final) &&
      Boolean(manifest.ci.jobUrl));
  manifest.result =
    validationsPassed && ciRepositoryValid && manifest.executionContext.valid
      ? "passed"
      : "failed";
  writeManifest();
  process.exitCode = manifest.result === "passed" ? 0 : 1;
}

